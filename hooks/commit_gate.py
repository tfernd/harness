"""PreToolUse hook on Bash: in every project, a commit message follows `harness:git-commit`.

The commands are read as the guard reads them: past prefixes such as `env`, `sudo` or `command`, inside `bash -c` and the
other strings the guard reads, from the folder a `cd` or `git -C` moves to. The message comes from `-m` (`-mX`, `--message=`
and a prefix such as `--mess` too), `-F` or a heredoc in the same command. A subject is `type(scope): summary` with no
trailing period, then a blank line and `* ` or `- ` bullets, then an optional footer. Git's own subjects (merge, revert,
fixup) pass. A commit whose message cannot be read is refused, with the way to pass one: a variable or a substitution
with no heredoc, a `-F` file that does not exist or that the same command writes, `-F -` with no heredoc, a reused message
(`-C`, `-c`), or none at all (the editor). `guard.commit_style: false` in the owner file turns the rule off.

AI attribution, refused in a commit, a tag, a merge, `commit-tree` and a pull request or its comment: after NFKC, with
zero-width characters dropped and Cyrillic or Greek lookalikes read as Latin, a `Co-authored-by`, `Assisted-by`,
`Generated-by` or `Signed-off-by` naming an AI tool or model, a line that opens with "Generated with", "Generated by" or
"Made with" and the name right after, or a robot emoji. Read: the messages, `--trailer` values, a pull request's `--title`,
`--body` and `--body-file`, and the `-f`/`-F` fields of `gh api` (`-F key=@file` reads the file); an `--author` or a
`git -c user.name=` / `user.email=` naming one is refused too.

Tests kept: a `git commit` that leaves fewer test definitions in the changed test files than HEAD holds is refused, naming the files and
counts, unless the message has a bullet `* Tests removed: <reason>`. A test file is `test_*.py`, `*_test.py`, `*_test.go`, `*.test.*`,
`*.spec.*`, any `.rs` file or any file under a `tests/` or `test/` folder. A definition is a Python `test_` function whose body is more than
`pass`, `...` or a docstring, and that no `skip` decorator marks (read by `ast`, so one in a string does not count), `it(` / `test(` (JS and TS; `it.skip`, `test.skip` and `xit` are not), `func Test` (Go) or `#[test]`
(Rust). The staged files are compared; with `-a`/`--all`, or after a `git add` in the same command, the tracked working-tree files are, and
with paths (`git commit <paths>`) those paths in the working tree. The tests of all changed files are summed, so a rename or a move that
keeps them passes. A first commit, an unreadable repository or a git call past 3 seconds passes. `tests_kept.enabled: false` turns this
part off.
"""

