class OptionSpec(NamedTuple):
    """The options of one command: each short letter's long name, the ones that take a value, and every long name."""

    short: dict[str, str]  # keys are data: a letter and the long option it stands for
    values: frozenset[str]  # the long options that take a value, attached (`=`, or after the letter) or in the next word
    names: frozenset[str]  # every long option, so a unique prefix can be read as one


class ParsedOptions(NamedTuple):
    """A command's arguments sorted into option values, flags and operands."""

    values: dict[str, list[str]]  # keys are data: a long option and each value given to it
    flags: set[str]  # the long names of the flags given
    operands: list[str]  # the other words, every word after `--` included


class Call(NamedTuple):
    """A git or gh command a shell command runs."""

    words: list[str]  # the command word and its arguments
    directory: str | None  # the folder it runs in, None when not known
    written: list[str]  # the absolute paths the steps before it write


